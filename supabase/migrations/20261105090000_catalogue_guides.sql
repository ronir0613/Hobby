-- and tags for the starting quiz (step 15); each starter idea gets steps, minutes and a
-- difficulty (easy -> moderate -> stretch).
--
-- Upserts by slug, and by (interest, sort_order) for starter ideas, so the 9 original interests
-- and their first starter idea keep their ids (attempts reference both). Nothing is deleted.
-- Starter idea steps are stored in `instructions`, one step per line.

