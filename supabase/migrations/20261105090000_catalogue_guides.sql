alter table public.interests
  add column needs text,
  add column setting text check (setting in ('indoor', 'outdoor', 'either')),
  add column social text check (social in ('solo', 'together', 'either')),
  add column session_minutes integer check (session_minutes > 0),
  add column cost text check (cost in ('free', 'low', 'medium')),
  add column moods text[] check (
    cardinality(moods) between 1 and 4
    and moods <@ array['calm', 'creative', 'active', 'learning']::text[]
  );

comment on column public.interests.needs is 'What you''ll need, one short line.';
comment on column public.interests.setting is 'Quiz tag: indoor, outdoor or either.';
comment on column public.interests.social is 'Quiz tag: solo, together or either.';
comment on column public.interests.session_minutes is 'Quiz tag: a typical session, in minutes.';
comment on column public.interests.cost is 'Quiz tag: free, low (a small one-off buy) or medium (some kit).';
comment on column public.interests.moods is 'Quiz tags: calm, creative, active, learning.';

alter table public.starter_ideas
  add constraint starter_ideas_difficulty_check
