-- Step 17: the catalogue becomes 100 hobbies in 15 categories, with reference links and safety notes.
--
-- Upserts by slug, and by (interest, sort_order) for starter ideas, so existing ids stay the same.
-- Nothing is deleted: hobbies leaving the catalogue are unpublished, and attempts on them keep working.
-- An attempt on a leaving hobby keeps its name through custom_title, since RLS hides the hobby itself.

