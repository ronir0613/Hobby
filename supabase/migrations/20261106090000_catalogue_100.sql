alter table public.interests add column safety_note text;
comment on column public.interests.safety_note is 'One short safety line, shown under "What you''ll need". Null if none.';

create table public.starter_idea_links (
  id uuid primary key default gen_random_uuid(),
  starter_idea_id uuid not null references public.starter_ideas (id) on delete cascade,
  sort_order integer not null,
  title text not null check (length(title) > 0),
  url text not null check (url like 'https://%'),
  publisher text not null check (length(publisher) > 0),
  is_published boolean not null default false,
  unique (starter_idea_id, sort_order)
);
comment on table public.starter_idea_links is 'Reference links shown under a starter idea. Opened in the phone''s browser.';

alter table public.starter_idea_links enable row level security;

create policy starter_idea_links_read_published on public.starter_idea_links
  for select to anon, authenticated using (
    is_published and exists (
      select 1 from public.starter_ideas s
      join public.interests i on i.id = s.interest_id
      join public.categories c on c.id = i.category_id
      where s.id = starter_idea_id and s.is_published and i.is_published and c.is_published
    )
  );

revoke all on table public.starter_idea_links from public, anon, authenticated;
grant select on public.starter_idea_links to anon, authenticated;

